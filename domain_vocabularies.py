def get_domain_items(category_name: str, limit: int = 30) -> list[str]:
    name_l = category_name.lower()
    collected: list[str] = []
    seen: set[str] = set()

    # Sort by longest pattern first to prefer specific domains
    ranked = sorted(
        DOMAIN_ITEMS,
        key=lambda x: max(len(p) for p in x[0]),
        reverse=True,
    )

    for patterns, items in ranked:
        if any(p in name_l for p in patterns):
            for item in items:
                if item.lower() not in seen:
                    seen.add(item.lower())
                    collected.append(item)
                if len(collected) >= limit:
                    return collected
    return collected
